"""In-repo experiments: proxy re-encode variants and marker-relocation residuals.

This harness materializes the failure modes that distinguish the two
association schemes, all from synthetic shots already used by the test suite:

* ``reencode_healthy``  - pure downscale re-encode, time preserving;
* ``head_trim``         - first ``k`` source frames deleted (timecode shifts);
* ``mid_drop``          - frames deleted from the middle of the shot;
* ``rate_convert``      - frame-rate change with resample (e.g. 24 -> 30 fps);
* ``frozen_run``        - a range of source frames duplicated in the proxy,
  producing content that cannot be uniquely anchored.

Every variant is built from an explicit list of *source frame indices*, which
is the ground-truth correspondence: proxy frame ``p`` depicts source frame
``source_indices[p]``. Marker-relocation residuals and per-frame association
residuals are measured against that ground truth, and the whole JSON report is
deterministic and regenerated by re-running this script.

Run::

    python3 -I scripts/proxy_association_experiment.py [out_dir]
"""

import argparse
import glob
import json
import os
import site
import sys
import tempfile
import time

for _candidate in glob.glob(
    os.path.expanduser("~/.local/lib/python*/site-packages")
):
    if os.path.isdir(_candidate) and _candidate not in sys.path:
        site.addsitedir(_candidate)

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from PIL import Image, ImageDraw  # noqa: E402

from proxyworkstation.core.ffutils import ffmpeg_bin, make_proxy, probe  # noqa: E402
from proxyworkstation.experimental import (  # noqa: E402
    TimeMappingResolver,
    build_content_resolver,
    relocate_marker,
)
from scripts.make_samples import PALETTE  # noqa: E402

ANCHOR_STEPS = (1, 2, 4, 8)
GRID = 16


# --------------------------------------------------------------------------
# Ground-truth variant construction
# --------------------------------------------------------------------------


def _render_source_frames(shot_id, width, height, frame_count, tmpdir):
    base = PALETTE.get(shot_id, (90, 90, 90))
    paths = []
    for n in range(frame_count):
        img = Image.new("RGB", (width, height), base)
        draw = ImageDraw.Draw(img)
        band_x = int((n / max(1, frame_count - 1)) * (width - 120))
        draw.rectangle([band_x, 0, band_x + 120, height], fill=(255, 255, 255))
        draw.text((24, 18), f"{shot_id} EXPERIMENT", fill=(255, 255, 0))
        draw.text((24, height // 2 - 40), f"FRAME {n:04d}", fill=(0, 0, 0))
        p = os.path.join(tmpdir, f"src_{n:05d}.png")
        img.save(p)
        paths.append(p)
    return paths


def _encode_png_sequence(png_paths, out_path, fps):
    import subprocess

    # A unique temp directory per encode: build_variant nests a full-res
    # encode inside the driver's own TemporaryDirectory, so reusing one name
    # races on the frame sequence.
    with tempfile.TemporaryDirectory(prefix="proxy_seq_") as seq_dir:
        for i, p in enumerate(png_paths):
            # Re-save pixels rather than hard-link/copy: duplicate-source
            # variants (frozen runs) repeat the same path, and a filesystem
            # copy would leave gaps when identical names overwrite each other.
            Image.open(p).save(os.path.join(seq_dir, f"f_{i:05d}.png"))
        cmd = [
            ffmpeg_bin(), "-y", "-v", "error",
            "-framerate", str(int(fps)),
            "-i", os.path.join(seq_dir, "f_%05d.png"),
            "-c:v", "libx264", "-preset", "medium", "-crf", "16",
            "-pix_fmt", "yuv420p",
            out_path,
        ]
        subprocess.run(cmd, check=True, capture_output=True, text=True)


def build_variant(source_pngs, variant, out_dir, source_fps):
    """Return (proxy_path, source_indices, declared_params) for a variant.

    ``source_indices[p]`` is the source frame depicted by proxy frame ``p`` -
    the ground truth every residual is measured against.
    """
    n = len(source_pngs)
    if variant == "reencode_healthy":
        indices = list(range(n))
        fps = source_fps
        offset = 0
    elif variant == "head_trim":
        k = 4
        indices = list(range(k, n))
        fps = source_fps
        offset = 0  # declared parameters pretend the clip starts at zero
    elif variant == "mid_drop":
        drop = set(range(8, 12))
        indices = [i for i in range(n) if i not in drop]
        fps = source_fps
        offset = 0
    elif variant == "rate_convert":
        # 24 fps source re-timed to 30 fps by nearest-frame resample.
        target_fps = 30
        length = round(n * target_fps / source_fps)
        indices = [min(n - 1, int(round(p * source_fps / target_fps)))
                   for p in range(length)]
        fps = target_fps
        offset = 0
    elif variant == "frozen_run":
        # Frames 10..13 are frozen onto the content of frame 9.
        indices = list(range(n))
        for p in range(10, 14):
            indices[p] = 9
        fps = source_fps
        offset = 0
    else:
        raise ValueError(f"unknown variant {variant}")

    proxy_full = os.path.join(out_dir, f"{variant}_full.mp4")
    proxy_path = os.path.join(out_dir, f"{variant}.mp4")
    os.makedirs(out_dir, exist_ok=True)
    chosen = [source_pngs[i] for i in indices]
    _encode_png_sequence(chosen, proxy_full, fps)
    # Downscale to proxy resolution through the production encoder path.
    make_proxy(proxy_full, proxy_path, height=270)
    declared = {
        "source_fps": source_fps,
        "proxy_fps": fps,
        "start_offset": offset,
    }
    return proxy_path, indices, declared


# --------------------------------------------------------------------------
# Residual measurement
# --------------------------------------------------------------------------


def _time_resolver(source_meta, proxy_meta, declared, source_indices):
    """Two provenance stances for the time-map scheme."""
    naive = TimeMappingResolver(
        source_fps=declared["source_fps"],
        proxy_fps=declared["proxy_fps"],
        source_frame_count=source_meta["frame_count"],
        proxy_frame_count=proxy_meta["frame_count"],
        start_offset=declared["start_offset"],
        provenance="declared-parameters",
    )
    coverage = set(source_indices)
    informed = TimeMappingResolver(
        source_fps=declared["source_fps"],
        proxy_fps=declared["proxy_fps"],
        source_frame_count=source_meta["frame_count"],
        proxy_frame_count=proxy_meta["frame_count"],
        start_offset=source_indices[0],
        coverage=coverage,
        provenance="exact-transform-log",
    )
    return naive, informed


def forward_residuals(resolver, source_indices):
    """Per-proxy-frame residual between resolver answer and ground truth."""
    rows = []
    for proxy_frame, truth_source in enumerate(source_indices):
        res = resolver.resolve_proxy_frame(proxy_frame)
        residual = (
            abs(res.source_frame - truth_source)
            if res.source_frame is not None else None
        )
        rows.append({
            "proxy_frame": proxy_frame,
            "truth_source": truth_source,
            "resolved_source": res.source_frame,
            "status": res.status,
            "residual": residual,
            "detail": res.detail,
        })
    return rows


def _summarize(rows):
    numeric = [r["residual"] for r in rows if r["residual"] is not None]
    statuses = {}
    for r in rows:
        statuses[r["status"]] = statuses.get(r["status"], 0) + 1
    ambiguous = [r["proxy_frame"] for r in rows if r["status"] == "ambiguous"]
    weak = [r["proxy_frame"] for r in rows if r["status"] == "weak_match"]
    unmatched = [r["proxy_frame"] for r in rows if r["status"] in
                 ("unmatched", "out_of_range")]
    return {
        "frames": len(rows),
        "max_abs_residual": max(numeric) if numeric else None,
        "mean_abs_residual": round(sum(numeric) / len(numeric), 3) if numeric else None,
        "exact_frames": sum(1 for r in rows if r["residual"] == 0),
        "status_counts": statuses,
        "ambiguous_frames": ambiguous,
        "weak_match_frames": weak,
        "unreliable_frames": ambiguous + weak + unmatched,
    }


def marker_residuals(resolver, marker_frames, source_indices):
    """Relocate edit markers and measure residual against ground truth."""
    truth_by_source = {}
    for proxy_frame, src in enumerate(source_indices):
        truth_by_source.setdefault(src, proxy_frame)
    rows = []
    for marker in marker_frames:
        rel = relocate_marker(resolver, marker)
        truth_proxy = truth_by_source.get(marker)
        residual = None
        if rel["proxy_frame"] is not None and truth_proxy is not None:
            residual = abs(rel["proxy_frame"] - truth_proxy)
        elif rel.get("nearest_source_frame") is not None:
            residual = abs(rel["nearest_source_frame"] - marker)
        rows.append({
            "source_marker": marker,
            "truth_proxy_frame": truth_proxy,
            "relocated_proxy_frame": rel["proxy_frame"],
            "status": rel["status"],
            "residual": residual,
            "round_trip_source_residual": rel.get("residual"),
            "reason": rel["reason"],
        })
    return rows


# --------------------------------------------------------------------------
# Experiment driver
# --------------------------------------------------------------------------


def run_experiment(out_dir, shot_id="SHOT_A", width=960, height=540,
                   frame_count=24, fps=24.0):
    os.makedirs(out_dir, exist_ok=True)
    cache_dir = os.path.join(out_dir, "fp_cache")
    variants = (
        "reencode_healthy",
        "head_trim",
        "mid_drop",
        "rate_convert",
        "frozen_run",
    )
    # Markers spread across the shot, including inside the frozen/dropped runs.
    marker_frames = [0, 3, 6, 9, 11, 13, 17, 23]

    with tempfile.TemporaryDirectory(prefix="proxy_assoc_") as work:
        source_path = os.path.join(work, f"{shot_id}.mp4")
        src_png_dir = os.path.join(work, "src_png")
        os.makedirs(src_png_dir)
        pngs = _render_source_frames(shot_id, width, height, frame_count, src_png_dir)
        _encode_png_sequence(pngs, source_path, fps)
        source_meta = probe(source_path)

        report = {
            "shot_id": shot_id,
            "source": {
                "frame_count": source_meta["frame_count"],
                "fps": source_meta["fps"],
                "width": source_meta["width"],
                "height": source_meta["height"],
            },
            "marker_frames": marker_frames,
            "grid": GRID,
            "anchor_steps": list(ANCHOR_STEPS),
            "variants": {},
        }

        for variant in variants:
            variant_dir = os.path.join(out_dir, variant)
            os.makedirs(variant_dir, exist_ok=True)
            t0 = time.perf_counter()
            proxy_path, source_indices, declared = build_variant(
                pngs, variant, variant_dir, fps
            )
            build_seconds = round(time.perf_counter() - t0, 3)
            proxy_meta = probe(proxy_path)

            naive_time, informed_time = _time_resolver(
                source_meta, proxy_meta, declared, source_indices
            )

            variant_report = {
                "proxy_frame_count": proxy_meta["frame_count"],
                "proxy_fps": proxy_meta["fps"],
                "ground_truth_source_indices": source_indices,
                "build_seconds": build_seconds,
                "schemes": {},
            }

            # Scheme A: time mapping, both provenance stances.
            for label, resolver in (
                ("time_map_declared", naive_time),
                ("time_map_informed", informed_time),
            ):
                rows = forward_residuals(resolver, source_indices)
                markers = marker_residuals(resolver, marker_frames, source_indices)
                variant_report["schemes"][label] = {
                    "forward": _summarize(rows),
                    "markers": _summarize_markers(markers),
                    "marker_rows": markers,
                    "index": resolver.describe_index(),
                    "forward_rows": rows,
                }

            # Scheme B: content anchors at several sparsity levels.
            for step in ANCHOR_STEPS:
                t0 = time.perf_counter()
                resolver = build_content_resolver(
                    source_path, proxy_path, grid=GRID,
                    anchor_step=step, cache_dir=cache_dir,
                )
                index_seconds = round(time.perf_counter() - t0, 3)
                rows = forward_residuals(resolver, source_indices)
                markers = marker_residuals(resolver, marker_frames, source_indices)
                index_info = resolver.describe_index()
                index_info["index_build_seconds"] = index_seconds
                variant_report["schemes"][f"content_anchor_step{step}"] = {
                    "forward": _summarize(rows),
                    "markers": _summarize_markers(markers),
                    "marker_rows": markers,
                    "index": index_info,
                    "forward_rows": rows,
                }

            report["variants"][variant] = variant_report

    report_path = os.path.join(out_dir, "association_report.json")
    with open(report_path, "w", encoding="utf-8") as fh:
        json.dump(report, fh, indent=2, ensure_ascii=False)
    return report, report_path


def _summarize_markers(rows):
    located = [r for r in rows if r["relocated_proxy_frame"] is not None]
    exact = [r for r in located if r["residual"] == 0]
    ambiguous = [r["source_marker"] for r in rows if r["status"] == "ambiguous"]
    weak = [r["source_marker"] for r in rows if r["status"] == "weak_match"]
    failed = [r["source_marker"] for r in rows
              if r["relocated_proxy_frame"] is None]
    numeric = [r["residual"] for r in rows if r["residual"] is not None]
    return {
        "markers": len(rows),
        "located": len(located),
        "exact": len(exact),
        "ambiguous_markers": ambiguous,
        "weak_match_markers": weak,
        "unrelocatable_markers": failed,
        "max_abs_residual": max(numeric) if numeric else None,
    }


def print_summary(report):
    print(f"\nShot {report['shot_id']}: {report['source']['frame_count']} "
          f"frames @ {report['source']['fps']:g}fps, grid {report['grid']}")
    header = f"{'variant':<17}{'scheme':<24}{'fwd max|d|':>11}{'fwd mean':>10}{'markers exact':>14}{'unreliable':>12}"
    print(header)
    print("-" * len(header))
    for variant, vr in report["variants"].items():
        for scheme, sr in vr["schemes"].items():
            fwd = sr["forward"]
            mk = sr["markers"]
            print(
                f"{variant:<17}{scheme:<24}"
                f"{str(fwd['max_abs_residual']):>11}"
                f"{str(fwd['mean_abs_residual']):>10}"
                f"{mk['exact']:>7}/{mk['markers']:<6}"
                f"{len(fwd['unreliable_frames']):>12}"
            )
        print()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "out_dir", nargs="?", default="experiments/proxy_association",
        help="output directory for variants, cache and JSON report "
             "(generated media/cache are git-ignored; the JSON is committed)",
    )
    args = parser.parse_args()
    report, report_path = run_experiment(args.out_dir)
    print_summary(report)
    print(f"Full report (regenerable data): {os.path.abspath(report_path)}")
